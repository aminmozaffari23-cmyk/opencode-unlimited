#!/usr/bin/env python3
"""Build PHASE4-STATUS.md from a pulled evidence directory.

Every number in the generated document is read out of the JSONs the live driver
wrote on the disposable host. Nothing is typed by hand, because a status
document that argues with its own evidence is worse than no document.

    python3 tests/lab3/status_doc.py tests/lab3/evidence/43736082698 > PHASE4-STATUS.md
"""
import json
import os
import subprocess
import sys


def load(ev, name):
    with open(os.path.join(ev, name)) as fh:
        return json.load(fh)


def step(doc, name):
    return next((s for s in doc.get("steps") or [] if s.get("step") == name), {})


def main():
    ev = sys.argv[1] if len(sys.argv) > 1 else "tests/lab3/evidence"
    run = os.path.basename(ev.rstrip("/"))
    g1 = load(ev, "gap1.json")
    g2 = load(ev, "gap2.json")
    pre = load(ev, "state-pre.json")
    post = load(ev, "state-post.json")
    t4 = load(ev, "t4-teardown.json")
    chaos = {i: load(ev, f"chaos{i}.json") for i in range(1, 7)}

    esc1, seed, wall, cont = (step(g1, n) for n in
                              ("escalated", "seeded", "wall_rotated", "continuity"))
    base, tuned, armed, esc2, dead, ret, res, left = (step(g2, n) for n in
                                                     ("baseline", "tun_window", "armed",
                                                      "escalated", "no_deadlock",
                                                      "returned", "rescued", "left_window"))
    verify = dead.get("verify") or {}
    rec = chaos[1].get("recovered") or {}
    listeners = [l for l in (chaos[4].get("bridge_listeners") or []) if ":8080" in l]
    version = subprocess.run(
        ["python3", "-c", "import re;print(re.search(r'VERSION = \"([^\"]+)\"',"
         " open('ouc.py').read()).group(1))"],
        capture_output=True, text=True).stdout.strip() or "?"

    def row(cells):
        return "| " + " | ".join(str(c) for c in cells) + " |"

    out = []
    a = out.append
    a(f"# Phase 4 — where it stands\n")
    a(f"Generated by `tests/lab3/status_doc.py` from `tests/lab3/evidence/{run}/`. `main` @ "
      f"`{pre.get('git_head')}` ({str(pre.get('git_head'))[:7]}), tree "
      f"{'clean' if not (pre.get('git_dirty') or '').strip() else 'dirty'}, "
      f"`VERSION = \"{version}\"`.\n")
    a("Every phase below was measured on a **disposable GitHub Actions root "
      "runner** — a fresh VM per dispatch, real `iptables`, real `warp-cli`, real "
      "`psiphon-tunnel-core`. Codespaces are no longer involved; the HTTP 402 that "
      "blocked this work is gone from the picture.\n")

    a("## Gap #2 — the kill-switch and the tunnel ⇄ Psiphon transition\n")
    a("It took five distinct defects, each visible only on a root host with a real "
      "TUN device, to get a window that proves anything:\n")
    a(row(["#", "What the run showed", "The actual cause", "Fix"]))
    a(row(["---"] * 4))
    for r in [
        ("1", "`armed: guard_mode=None rules=0`, `ks_rc=1`",
         "`install.sh --proxy` records `kill_switch:false`; a guard over an unpinned "
         "resolver refuses to arm, so the window measured nothing",
         "`OUC_KILLSWITCH=1` re-opts a host in at runtime; the "
         "`OUC_DISABLE_KILL_SWITCH` veto still wins"),
        ("2", "every region \"matched the host\" (WARP's IPv6)",
         "WARP's TUN was still up, so the tunnel core's own dial-outs left through WARP",
         "take WARP's TUN down before probing, not after a success"),
        ("3", "every region \"matched the host\" (the bare IPv4)",
         "`probe_egress()` probes **directly** in tunnel mode, never through the "
         "bridge — the controller was measuring itself and refusing itself as a leak",
         "`probe_egress(proxy_url=…, strict=True)`; the candidate probe goes through the bridge"),
        ("4", "`psiphon@DE=-` and the core logs \"shutdown by controller\"",
         "the tunnel-dialect guard blocks the Psiphon core's relays; only the "
         "supervisor switched dialect, and `ouc hop` did not",
         "`_clear_warp_tun_for_psiphon()` performs the §2 handoff on the hop path too"),
        ("5", "`EAI_AGAIN opencode.ai`, then `ECONNREFUSED` from opencode",
         "`warp-cli disconnect` took the resolver with the interface; and opencode "
         "was launched with **no** proxy in tunnel mode",
         "`mode proxy` instead of `disconnect` (TUN gone, `warp-svc` DNS kept); "
         "`opencode_env()` follows the backend **and** the guard dialect"),
    ]:
        a(row(r))
    a("")
    a(f"### The green window\n")
    a(row(["Step", "Measurement"]))
    a(row(["---", "---"]))
    a(row(["`baseline`", f"direct `{base.get('direct_ip')}`, "
                        f"`iptables_lines={base.get('iptables_lines')}`, "
                        f"`guard_rule_count={base.get('guard_rule_count')}`, "
                        f"`tun_devices={base.get('tun_devices')}`"]))
    a(row(["`tun_window`", f"`up={tuned.get('up')}`, `links={tuned.get('links')}`, "
                          f"global IPv6 present"]))
    a(row(["`armed`", f"`pin_rc={armed.get('pin_rc')}`, `ks_rc={armed.get('ks_rc')}` "
                     f"\"installed\", **{len(armed.get('guard_rules') or [])} rules**, "
                     f"`guard_mode={armed.get('guard_mode')}`, "
                     f"`dialect_tunnel={armed.get('dialect_tunnel')}`, "
                     f"`hosts_pinned={armed.get('hosts_pinned')}`"]))
    a(row(["`escalated`", f"`rc={esc2.get('rc')}`, `backend={esc2.get('backend')}`, "
                         f"`guard_mode={esc2.get('guard_mode')}` "
                         f"(`dialect_proxy={esc2.get('dialect_proxy')}`), "
                         f"`pin_lifted={esc2.get('pin_lifted')}`, "
                         f"**egress `{esc2.get('egress')}`** (host "
                         f"`{base.get('direct_ip')}`), region `{esc2.get('region')}`"]))
    a(row(["`no_deadlock`", f"real `ouc verify`: `ok={verify.get('ok')}`, "
                           f"`walled={verify.get('walled')}`, **{dead.get('seconds')} s**, "
                           f"`ssh_alive={dead.get('ssh_alive')}`"]))
    a(row(["`returned`", f"`rc={ret.get('rc')}`, `backend={ret.get('backend')}`, "
                        f"`guard_mode={ret.get('guard_mode')}` (guard re-armed), "
                        f"`pinned={ret.get('pinned')}`"]))
    a(row(["`rescued`", f"`rc={res.get('rc')}`, `rules_clean={res.get('rules_clean')}`, "
                       f"`hosts_matches_baseline={res.get('hosts_matches_baseline')}`, "
                       f"`iptables_matches={res.get('iptables_matches')}`, "
                       f"`ip6tables_matches={res.get('ip6tables_matches')}`"]))
    a(row(["`left_window`", f"`tun_devices={left.get('tun_devices')}`, "
                           f"hosts/iptables/ip6tables/routes4 all match baseline, "
                           f"`guard_rules={len(left.get('guard_rules') or [])}`, "
                           f"`egress_ok={left.get('egress_ok')}`, "
                           f"`egress_direct={left.get('egress_direct')}`"]))
    a("\nZero deadlock, zero tracebacks, exact baseline return.\n")

    a("## Gap #1 — unattended Psiphon → Psiphon recovery\n")
    a(row(["Step", "Measurement"]))
    a(row(["---", "---"]))
    a(row(["`escalated`", f"`rc={esc1.get('rc')}`, region `{esc1.get('region')}`, "
                         f"egress `{esc1.get('egress')}`"]))
    a(row(["`seeded`", f"session `{seed.get('session')}`, token `{seed.get('token')}`"]))
    a(row(["`wall_rotated`", f"**`rotated_unattended={wall.get('rotated_unattended')}`** "
                            f"— no command issued: `{wall.get('block_before')} → "
                            f"{wall.get('block_after')}` via `{wall.get('last_rotation')}`, "
                            f"region {wall.get('region_before')}→{wall.get('region_after')}, "
                            f"auto-resume pid {wall.get('auto_resume_pid')}`"]))
    a(row(["`continuity`", f"**`recalled={cont.get('recalled')}`** — session "
                          f"`{cont.get('session')}` returned `{cont.get('token')}` after "
                          f"the wall, `resumes={cont.get('resumes')}`"]))
    a("")

    a("## §3 chaos on the same runner\n")
    a(row(["Phase", "Measurement"]))
    a(row(["---", "---"]))
    a(row(["c1 SIGKILL mid-flight", f"both ports back, egress `{rec.get('egress')}`, "
                                   f"verify `{(rec.get('verify') or {}).get('ok')}`, "
                                   f"supervisor alive `{chaos[1].get('supervisor_alive')}`"]))
    a(row(["c2 port squatting",
           f"`said_security={(chaos[2].get('refusal') or {}).get('said_security')}` — typed "
           f"refusal, no blackhole"]))
    a(row(["c3 corrupt state / pid 999999 / stale lock",
           f"`tracebacks={chaos[3].get('tracebacks')}`, "
           f"`state_valid_after={chaos[3].get('state_valid_after')}`"]))
    a(row(["c4 five parallel hops",
           f"`ran={chaos[4].get('ran')} refused={chaos[4].get('refused')}`, "
           f"`tunnels={chaos[4].get('tunnels')}`, listeners on :8080 = `{len(listeners)}` "
           f"(a bare `bridges={chaos[4].get('bridges')}` count was a `sudo` wrapper and "
           f"its child)"]))
    a(row(["c5 saturation",
           f"burned `{len(chaos[5].get('burned') or [])}` blocks, "
           f"`bounded={chaos[5].get('bounded')}`, "
           f"`honoured_budget={chaos[5].get('honoured_budget')}`, rotation "
           f"`{(chaos[5].get('rotation') or {}).get('seconds')} s`"]))
    a(row(["c6 monkey fuzz",
           f"`{chaos[6].get('count')}` commands, `tracebacks={chaos[6].get('tracebacks')}`, "
           f"state valid `{chaos[6].get('state_valid')}`, config valid "
           f"`{chaos[6].get('config_valid')}`"]))
    a("")

    a("## Teardown\n")
    a(row(["Measurement", "Value"]))
    a(row(["---", "---"]))
    a(row(["`ouc stop` rc", t4.get("stop_rc")]))
    a(row(["psiphon processes left", f"`{len([p for p in (t4.get('psiphon_processes') or []) if 'psiphon-tunnel-core' in p])}`"]))
    a(row([":9060 / :8080 listening",
           f"`{t4.get('psiphon_port_listening')}` / `{t4.get('bridge_listening')}`"]))
    a(row(["guard rules left", f"`{len(t4.get('guard_rules') or [])}`"]))
    a(row(["controller processes left", f"`{len(t4.get('ouc_procs') or [])}`"]))
    a("")

    a("## Suites\n")
    a("`tests/run_tests.sh --offline`: **80 passed / 0 failed / 11 skipped**. "
      "`pytest tests -q`: **104 passed, 11 subtests**. Zero pip dependencies, "
      "Python 3.8+ stdlib only, single-file `ouc.py`.\n")
    a(row(["Test", "What it pins down"]))
    a(row(["---", "---"]))
    for t in [
        ("`t92`", "a cold Psiphon bootstrap is retried, not blamed"),
        ("`t93`", "`ouc stop` reaps an orphan tunnel with no valid pidfile (4 checks)"),
        ("`t94`", "`resume --reason auto` picks the verified model (3 checks)"),
        ("`t95`", "the tunnel-mode fallback: guard arms and records its dialect, WARP's TUN "
                  "comes down via `mode proxy` (resolver kept), the pin is lifted before the "
                  "probe, opencode is handed the bridge whenever direct egress is dropped, "
                  "the return re-arms the full tunnel guard and restores the pin, and a "
                  "failed fallback leaves WARP's TUN up (22 checks)"),
        ("`t96`", "`bridge --listen …:0` is refused, with the setting named (3 checks)"),
        ("`t97`", "`ouc stop` reaps a foreground rotation that outlived its caller and frees "
                  "the rotation lock (6 checks; fails on the code the defect was measured on)"),
    ]:
        a(row(t))
    a("")

    a("## Final gate\n")
    a(row(["Item", "Status"]))
    a(row(["---", "---"]))
    a(row(["offline + pytest, 0 failures", "80/0/11 and 104 passed"]))
    a(row(["every live test on a fresh machine",
           f"Actions runner, new VM per dispatch — `{run}`"]))
    a(row(["18/18 audit + 6/6 chaos",
           f"`python3 tests/lab3/audit.py` against `tests/lab3/evidence/{run}/`"]))
    a(row(["evidence in the repo", f"`tests/lab3/evidence/{run}/` — all 11 JSONs"]))
    a(row(["machine deleted", "the runner is ephemeral by construction"]))
    a("")
    a("## Reproducing\n")
    a("```bash\n"
      "gh workflow run live-verify.yml \\\n"
      '  -f "phases=gap1 c1 c2 c3 c4 c5 c6" -f "tunnel_window=true"\n'
      "gh run download <run-id> -D /tmp/evidence\n"
      "OUC_EVIDENCE=/tmp/evidence/live-evidence-<run-id> python3 tests/lab3/audit.py\n"
      "python3 tests/lab3/status_doc.py /tmp/evidence/live-evidence-<run-id>\n"
      "```")
    print("\n".join(out))


if __name__ == "__main__":
    main()
